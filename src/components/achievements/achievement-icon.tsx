import {
  Award,
  BadgeCheck,
  BookOpen,
  CalendarCheck,
  CheckCheck,
  ChevronsUp,
  Crown,
  Flag,
  Flame,
  Gem,
  GitBranch,
  Moon,
  Palette,
  PartyPopper,
  Repeat,
  Shield,
  Skull,
  Sparkles,
  Sunrise,
  Swords,
  Timer,
  Users,
  Zap,
  type LucideIcon,
} from "lucide-react";

const ICONS: Record<string, LucideIcon> = {
  swords: Swords,
  sparkles: Sparkles,
  repeat: Repeat,
  flame: Flame,
  "calendar-check": CalendarCheck,
  "git-branch": GitBranch,
  "chevrons-up": ChevronsUp,
  "book-open": BookOpen,
  palette: Palette,
  crown: Crown,
  timer: Timer,
  flag: Flag,
  "check-check": CheckCheck,
  gem: Gem,
  skull: Skull,
  shield: Shield,
  users: Users,
  "badge-check": BadgeCheck,
  zap: Zap,
  sunrise: Sunrise,
  moon: Moon,
  "party-popper": PartyPopper,
};

export function AchievementIcon({ name, className }: { name: string; className?: string }) {
  const Icon = ICONS[name] ?? Award;
  return <Icon aria-hidden className={className} />;
}
